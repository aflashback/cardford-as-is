function witness(def, index = 0) {
  if (def.$ref) return witness(schema.$defs[def.$ref.slice(8)], index);
  if (Object.hasOwn(def,'const')) return def.const;
  if (def.enum) return def.enum[index % def.enum.length];
  if (def.anyOf || def.oneOf) return witness((def.anyOf ?? def.oneOf)[0], index);
  if (def.type === 'null') return null;
  if (def.type === 'boolean') return false;
  if (def.type === 'number' || def.type === 'integer') return def.minimum ?? 0;
  if (def.type === 'string') {
    if (def.pattern?.startsWith('^[CDHS]')) return ['C2','D3','H4','S5'][index % 4];
    if (def.pattern?.includes('{8}-')) return '11111111-2222-3333-4444-555555555555';
    if (def.pattern === '^[a-f0-9]{48}$') return 'a'.repeat(48);
    if (def.pattern?.includes('\\.')) return '1.0.0';
    if (def.pattern?.includes('[0-9]')) return '1';
    return ('x'+index).padEnd(def.minLength ?? 0,'x');
  }
  if (def.type === 'array') return Array.from({length:def.minItems ?? 0}, (_,i)=>witness(def.items,i));
  if (def.type === 'object') {
    const value=Object.fromEntries((def.required ?? []).map(key=>[key,witness(def.properties[key],index)]));
    const applyConditional = rule => {
      for (const child of rule.allOf ?? []) applyConditional(child);
      if (!rule.if) return;
      const matches = (rule.if.required ?? []).every(key=>Object.hasOwn(value,key)) &&
        Object.entries(rule.if.properties ?? {}).every(([key,condition])=>value[key]===condition.const);
      const branch = matches ? rule.then : rule.else;
      // Conditional object schemas constrain an existing witness; replacing it
      // with a partial object would drop required fields from its base schema.
      const overlay = (target, properties) => {
        for (const [key,condition] of Object.entries(properties ?? {})) {
          if (condition === false) { delete target[key]; continue; }
          if (condition === true) continue;
          if (condition.type === 'object' || condition.properties) {
            target[key] ??= {};
            overlay(target[key],condition.properties);
          } else target[key]=witness(condition,index);
        }
      };
      overlay(value,branch?.properties);
    };
    applyConditional(def);
    return value;
  }
  throw new Error('Unsupported witness shape '+JSON.stringify(def));
}
